import fs from 'node:fs/promises';
import path from 'node:path';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const root = path.resolve(import.meta.dirname, '..');
const base = path.join(root, 'qa/risk_npv_layout_fix');
const wb = Workbook.create();
const sheet = wb.worksheets.add('假设');
const count = 1826;
sheet.getRange(`X7:X${count}`).values = [['已按香港政府公布假期及HKEX证券交易规则核验；半日市仍为有效交易日']];
sheet.getRange('X:X').format.columnWidth = 46;
sheet.getRange(`X7:X${count}`).format.font.name = 'Microsoft YaHei';
sheet.getRange(`X7:X${count}`).format.font.size = 10;
sheet.getRange(`X7:X${count}`).format.wrapText = true;
sheet.getRange(`X7:X${count}`).format.horizontalAlignment = 'left';
sheet.getRange(`X7:X${count}`).format.verticalAlignment = 'top';
sheet.getRange(`X7:X${count}`).format.rowHeight = 48;
wb.recalculate();
const output = await SpreadsheetFile.exportXlsx(wb);
await output.save(path.join(base, 'calendar_state_layout.xlsx'));
console.log(JSON.stringify({ output: path.join(base, 'calendar_state_layout.xlsx') }));
